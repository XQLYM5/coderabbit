/**
 * Compute the sum or concatenation of two values.
 * @param {*} a - First operand; will be combined with `b` using JavaScript `+` semantics.
 * @param {*} b - Second operand; will be combined with `a` using JavaScript `+` semantics.
 * @returns {*} The result of applying JavaScript's `+` operator to `a` and `b`.
 */
function add(a, b) {
  return a + b;
}