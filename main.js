/**
 * Compute the sum of two values.
 *
 * @param {number|string} a - The first addend.
 * @param {number|string} b - The second addend.
 * @returns {number|string} The numeric sum if both arguments are numbers, or the concatenated string if either argument is a string.
 */
function add(a, b) {
  return a + b;
}