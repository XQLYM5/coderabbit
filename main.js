/**
 * Apply the JavaScript `+` operator to two operands.
 *
 * @param {number|string} a - First operand.
 * @param {number|string} b - Second operand.
 * @returns {number|string} The result of `a + b`: numeric sum for numbers or string concatenation if either operand is a string.
 */
function add(a, b) {
  return a + b;
}